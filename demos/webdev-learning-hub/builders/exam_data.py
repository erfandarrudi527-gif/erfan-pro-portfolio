def render_exam_card(exam):
    """Generate HTML for an interactive Exam Checkpoint Card"""
    exam_id = exam["id"]
    title = exam["title"]
    desc = exam["desc"]
    questions = exam["questions"]
    q_count = len(questions)

    questions_html = ""
    for idx, q_item in enumerate(questions, start=1):
        q_raw = q_item["q"]
        if "\n" in q_raw:
            parts = q_raw.split("\n", 1)
            q_header_text = parts[0]
            code_part = parts[1]
            q_text = f'{q_header_text}<pre style="margin-top:8px; padding:10px 14px; background:rgba(2,6,23,0.85); border:1px solid rgba(56,189,248,0.25); border-radius:8px; direction:ltr; text-align:left; font-family:\'Fira Code\', monospace; color:#38bdf8; font-size:12px; line-height:1.6; overflow-x:auto;"><code>{code_part.replace("<", "&lt;").replace(">", "&gt;")}</code></pre>'
        else:
            q_text = q_raw

        opts = q_item["options"]
        correct_idx = q_item["correct"]
        expl = q_item["explanation"].replace('"', '&quot;')

        options_html = ""
        for opt_idx, opt_text in enumerate(opts):
            is_correct_attr = "true" if opt_idx == correct_idx else "false"
            options_html += f"""
            <div class="exam-option" data-correct="{is_correct_attr}" onclick="handleOptionSelect(this, '{exam_id}', {idx-1})">
              <span class="exam-opt-indicator"></span>
              <span class="exam-opt-text">{opt_text}</span>
            </div>
            """

        questions_html += f"""
        <div class="exam-question-box" data-qid="{idx-1}">
          <div class="exam-q-header">
            <span class="exam-q-badge">پرسش {idx} از {q_count}</span>
            <div class="exam-q-text">{q_text}</div>
          </div>
          <div class="exam-options-list">
            {options_html}
          </div>
          <div class="exam-expl-box" style="display:none;">
            <div class="exam-expl-title">💡 تحلیل پاسخ و نکته طلایی مصاحبه:</div>
            <p class="exam-expl-text">{expl}</p>
          </div>
        </div>
        """

    return f"""
    <section class="exam-milestone-card" id="{exam_id}" data-exam-id="{exam_id}">
      <div class="exam-card-banner">
        <div class="exam-badge-tag">
          <span>🏆 آزمون جامع ارزیابی مهارت</span>
        </div>
        <h3 class="exam-title">{title}</h3>
        <p class="exam-desc">{desc}</p>
      </div>

      <div class="exam-body-content">
        <div class="exam-questions-container">
          {questions_html}
        </div>

        <div class="exam-footer-card">
          <div class="exam-score-display">
            <div class="score-meta">
              <span class="score-label">کارنامه و نمره این آزمون:</span>
              <span class="score-val" id="score-val-{exam_id}">۰ از {q_count} پاسخ صحیح</span>
            </div>
            <div class="score-bar-bg">
              <div class="score-bar-fill" id="score-fill-{exam_id}"></div>
            </div>
            <div class="score-feedback-text" id="score-fb-{exam_id}">برای ارزیابی، گزینه‌های مد نظر خود را انتخاب فرمایید.</div>
          </div>
          <div class="exam-actions-btn-group">
            <button class="exam-reset-btn" onclick="resetExam('{exam_id}')">🔄 آزمون مجدد</button>
          </div>
        </div>
      </div>
    </section>
    """

